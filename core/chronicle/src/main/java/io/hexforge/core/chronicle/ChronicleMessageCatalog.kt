    private val byKey: Map<String, BilingualMessageTemplate> = entriesList.associateBy { it.key }

    val allTemplates: List<BilingualMessageTemplate> get() = entriesList

    fun size(): Int = entriesList.size

    fun getOrNull(key: String): BilingualMessageTemplate? = byKey[key]

    fun format(
        key: String,
        params: Map<String, String> = emptyMap(),
    ): Pair<String, String> {
        val tpl = byKey[key]
            ?: return "Unknown event key: $key" to "رویداد ناشناخته: $key"
        return interpolate(tpl.templateEn, params) to interpolate(tpl.templateFa, params)
    }

    private fun interpolate(template: String, params: Map<String, String>): String {
        var result = template
        for ((k, v) in params) {
            result = result.replace("{$k}", v)
        }
        return result
    }

    private fun tpl(
        key: String,
        module: ModuleId,
        phase: ChroniclePhase,
        severity: ChronicleSeverity,
        en: String,
        fa: String,
    ) = BilingualMessageTemplate(
        key = key,
        module = module,
        defaultPhase = phase,
        defaultSeverity = severity,
        templateEn = en,
        templateFa = fa,
    )
